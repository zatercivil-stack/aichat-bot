async def main():
    # Sanity
    for e in EDITS:
        if len(e.body) > 1024:
            print(f'❌ msg {e.msg_id} body {len(e.body)} > 1024 (capt limit)')
            sys.exit(1)
        if not e.body.startswith(('🆓','🔐','🚫','💡','🧬','👓','🌅','📱','💼','📐','🎲','🔥','💖','☕','🧔','🐕','🤖','🥤','🎨','🎧','⏳','🤔','🎟','🎁','🧹','🔁','✍','⏱','🗂','⚙','🏖','⚠','📸','📽','🐱','🇯🇵','⚔','💐','😐','💰')):
            print(f'⚠ msg {e.msg_id} starts unusual')

    async with AsyncSessionFactory() as session:
        rows = (await session.execute(
            select(PresetPreview.preset_key, PresetPreview.position, PresetPreview.file_id)
        )).all()
    file_map = {(k, p): fid for k, p, fid in rows}

    bot = Bot(token=settings.BOT_TOKEN)
    results = []
    try:
        for i, e in enumerate(EDITS):
            fid = file_map.get((e.preset_key, e.position))
            if not fid:
                fid = file_map.get((e.preset_key, 1 - e.position))
            if not fid:
                results.append((e.msg_id, 'SKIP_NO_PHOTO', e.preset_key))
                continue

            status = None
            for attempt in range(4):
                try:
                    await bot.edit_message_media(
                        chat_id=CHANNEL, message_id=e.msg_id,
                        media=InputMediaPhoto(media=fid, caption=e.body, parse_mode='HTML'),
                    )
                    status = 'OK_MEDIA'
                    break
                except TelegramRetryAfter as rx:
                    await asyncio.sleep(rx.retry_after + 1)
                    continue
                except TelegramBadRequest as exc:
                    m = str(exc).lower()
                    if 'no media' in m or 'can' in m and 'edited' in m:
                        try:
                            await bot.edit_message_text(
                                chat_id=CHANNEL, message_id=e.msg_id,
                                text=e.body, parse_mode='HTML',
                                disable_web_page_preview=True,
                            )
                            status = 'OK_TEXT'
                            break
                        except TelegramBadRequest as e2:
                            status = f'FAIL:{str(e2)[:80]}'
                            break
                    status = f'FAIL:{str(exc)[:80]}'
                    break
            if status is None:
                status = 'RETRY_EXHAUSTED'

            results.append((e.msg_id, status, e.preset_key))
            sys.stdout.write(f'[{i+1}/{len(EDITS)}] msg={e.msg_id} {status}\n'); sys.stdout.flush()

            # DB insert (these posts weren't in channel_posts before)
            if status.startswith('OK'):
                try:
                    async with AsyncSessionFactory() as session:
                        await session.execute(
                            sql_insert(ChannelPost).values(
                                topic=e.topic, body=e.body, cta_type='neyra',
                                scheduled_at=datetime.now(timezone.utc),
                                published_at=datetime.now(timezone.utc),
                                message_id=e.msg_id, status='published',
                            )
                        )
                        await session.commit()
                except Exception as db_exc:
                    sys.stdout.write(f'  (DB insert skipped: {str(db_exc)[:60]})\n')

            await asyncio.sleep(3.2)
    finally:
        await bot.session.close()

    print()
    print('=== ИТОГ ===')
    ok = sum(1 for _,s,_ in results if s.startswith('OK'))
    fail = len(results) - ok
    print(f'OK: {ok}/{len(EDITS)}   FAIL/SKIP: {fail}')
    for mid, s, k in results:
        if not s.startswith('OK'):
            print(f'  ❌ msg={mid} [{k}] {s}')


if __name__ == '__main__':
    asyncio.run(main())
